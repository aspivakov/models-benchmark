export const JUDGE_SYSTEM_PROMPT = `You are an evaluator for a structured-data extraction benchmark. Your job is to score how well a model extracted specific fields from a job posting, by comparing the model's output against the ORIGINAL POSTING TEXT.

Critical principles:
1. The original posting text is the source of truth. The reference extraction is a guide — it was generated by another model and may have its own errors. If the model output is correct against the posting but disagrees with the reference, the model is correct.
2. For list fields (benefits, required_skills, nice_to_have_skills): an item is "hallucinated" if it is NOT supported by the posting text. An item is "missed" if it IS in the posting but absent from the model output. Reasonable paraphrase is not hallucination — "Medical insurance" and "Medical" referring to the same benefit are equivalent.
3. For required_skills vs nice_to_have_skills: postings often use language like "required", "must have", "should have" for one and "preferred", "nice to have", "bonus", "a plus" for the other. If the model put something in the wrong bucket but it IS in the posting, that's a precision miss in one field and a recall miss in the other — score it accurately.
4. For string fields (location, salary_range): score semantic equivalence. "Tallahassee, FL" ≈ "Tallahassee, Florida". "$55,000 - $90,000" ≈ "$55k-$90k annual". Empty string on both sides is a match.

Return JSON only, no prose, conforming to the schema provided.`;

export function buildJudgeUserMessage(args: {
  inputPosting: string;
  reference: Record<string, unknown>;
  modelOutput: Record<string, unknown>;
}): string {
  return `## Original posting text

${args.inputPosting}

## Reference extraction (guide, may contain errors)

${JSON.stringify(args.reference, null, 2)}

## Model output to evaluate

${JSON.stringify(args.modelOutput, null, 2)}

Score the model output. For list fields, list specific items in hallucinated/missed arrays — use the model's own wording for hallucinated, and the reference's wording (or your wording if reference missed it) for missed.`;
}
